import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const {computeThemes,filterReasons,parseRoute,themeForTicker,tickersLine,loosenFor,searchMatch}=new Function(`${readFileSync(new URL('../themes.js',import.meta.url),'utf8')};return THEME_TRACKER`)();
const c=(ticker,adr,dv,d,y,ext=2)=>({ticker,name:ticker,adr,dv,ext,ret:{d,y}});
const data={companies:{NVDA:c('NVDA',2.577,2e10,-2,17),META:c('META',3.1,1e9,-1,30),TSLA:c('TSLA',4,1e9,2,null),AAPL:c('AAPL',1.5,1e9,1,10)},themes:[{id:'mag-7',name:'Mag 7',tickers:['NVDA','META','TSLA','AAPL']}]};
assert.equal(computeThemes(data)[0].rows.length,4);
assert.equal(computeThemes(data,{query:'NVDA'}).length,1,'ticker search still surfaces the theme');
assert.equal(computeThemes(data,{query:'NVDA'})[0].rows[0].ticker,'NVDA');
assert.match(filterReasons(data.companies.NVDA,{minAdr:3})[0],/2.58% < 3%/);
assert.equal(computeThemes(data,{query:'NVDA',minAdr:2.5})[0].rows[0].ticker,'NVDA');
assert.equal(computeThemes(data,{minAdr:0})[0].rows.length,4);
assert.equal(computeThemes(data)[0].mean,0.5);
assert.equal(computeThemes(data,{query:'META'})[0].mean,0.5,'search must not redefine group return');
assert.equal(computeThemes(data,{window:'y'})[0].mean,30,'missing YTD is excluded, not zero');
const six={companies:{NVDA:{...data.companies.NVDA,adr:4,ret:{d:-2,h:40,y:17}},META:{...data.companies.META,ret:{d:-1,h:10,y:30}},TSLA:{...data.companies.TSLA,ret:{d:2,y:null}},AAPL:{...data.companies.AAPL,ret:{d:1,h:20,y:10}}},themes:data.themes};
assert.equal(computeThemes(six,{window:'h'})[0].mean,25,'6M mean averages liquid names that have a 6M reading');
const html=readFileSync(new URL('../index.html',import.meta.url),'utf8');
assert.match(html,/data-win="h"[^>]*>6M/, 'Themes window tab includes 6M');
assert.match(readFileSync(new URL('../themes.js',import.meta.url),'utf8'), /h: '6M'/);
assert.match(readFileSync(new URL('../scripts/update-themes.py',import.meta.url),'utf8'), /'h': r\.get\('ret6m'\)/);
assert.match(readFileSync(new URL('../themes.js',import.meta.url),'utf8'), /is-stale/);
assert.match(readFileSync(new URL('../themes.css',import.meta.url),'utf8'), /\.date\.is-stale \.dot/);
const rankFixture=JSON.parse(readFileSync(new URL('./fixtures/theme-ranks-catalog.json',import.meta.url),'utf8'));
const dailyRanked=computeThemes(rankFixture,{window:'d',scope:'all'}).filter(t=>t.id!=='unclustered' && Number.isFinite(t.mean));
assert.deepEqual(dailyRanked.map(t=>t.id),['oil-gas','mag-7','semiconductors'],'Python rank history uses the same daily means as Themes');
const monthRanked=computeThemes(rankFixture,{window:'m',scope:'all'}).filter(t=>t.id!=='unclustered' && Number.isFinite(t.mean));
assert.deepEqual(monthRanked.map(t=>t.id),['mag-7','semiconductors','oil-gas']);
assert.equal(filterReasons({...data.companies.META,ext:0},{aboveOnly:true}).length,1);
assert.equal(filterReasons({...data.companies.META,ext:null},{aboveOnly:true})[0],'50-day SMA unavailable');
assert.equal(filterReasons({...data.companies.META,ema10:-1},{above10:true})[0],'Not above 10 EMA');
assert.equal(filterReasons({...data.companies.META,ema21:2},{above21:true}).length,0);
assert.equal(filterReasons({...data.companies.META,sma200:null},{above200:true})[0],'200 SMA unavailable');
assert.equal(filterReasons({...data.companies.META,dist52h:12},{max52:10})[0].includes('52W'),true);
assert.equal(filterReasons({...data.companies.META,dist52h:8},{max52:10}).length,0);
assert.deepEqual(parseRoute('#themes/lookup/NVDA'),{query:'nvda',selected:null});
assert.deepEqual(parseRoute('#themes/lookup/BRK%2EB'),{query:'brk.b',selected:null});
assert.deepEqual(parseRoute('#themes/semiconductors'),{query:null,selected:'semiconductors'});
const both={companies:data.companies,themes:[{id:'semiconductors',name:'Semiconductors',tickers:['NVDA']},{id:'mag-7',name:'Mag 7',tickers:['NVDA','META','TSLA','AAPL']}]};
assert.equal(themeForTicker(both,'NVDA').id,'semiconductors');
assert.equal(themeForTicker(data,'AAPL').id,'mag-7');
assert.equal(tickersLine([{ticker:'NVDA'},{ticker:'META'}]),'NVDA, META');
const withA={companies:{...data.companies,'HEI.A':c('HEI.A',4,2e8,1,10)},themes:[{id:'aero',name:'Aerospace',tickers:['HEI.A','META']}]};
assert.equal(computeThemes(withA)[0].rows.some(r => r.ticker==='HEI.A'), false);
const mixed={companies:data.companies,themes:[{id:'semiconductors',name:'Semis',tickers:['META']},{id:'retail',name:'Retail',tickers:['TSLA']}]};
assert.deepEqual(computeThemes(mixed,{scope:'focus'}).map(t=>t.id),['semiconductors']);
assert.equal(computeThemes(mixed,{scope:'all'}).length,2);
assert.equal(computeThemes(mixed,{scope:'focus',query:'tsla'}).some(t=>t.id==='retail'),true);
const health={companies:data.companies,themes:[{id:'healthcare-biotech',name:'Healthcare',tickers:['META']}]};
assert.equal(computeThemes(health,{scope:'focus'})[0].id,'healthcare-biotech');
const mex={companies:{ASM:{ticker:'ASM',name:'Avino',adr:4,dv:1e8,does:'Mines silver, gold, and copper in Mexico and sells the metal.',ret:{d:1}}},themes:[{id:'silver-miners',name:'Silver Miners',tickers:['ASM']}]};
assert.equal(computeThemes(mex,{query:'mexico'})[0].rows[0].ticker,'ASM');
assert.equal(searchMatch('rents data center space and power','datacenter'), true);
assert.equal(searchMatch('rents data center space and power','data-center'), true);
assert.equal(searchMatch('Mines silver in Mexico','datacenter'), false);
assert.equal(searchMatch('NVDA NVIDIA','$nvda'), true);
assert.deepEqual(loosenFor({adr:2.577,dv:2e10,ext:3,ema10:1,ema21:1,sma200:1},{minAdr:3,minDv:100,aboveOnly:false,above10:false,above21:false,above200:false}),{minAdr:2.5,minDv:100,aboveOnly:false,above10:false,above21:false,above200:false});
console.log('Themes: assertions passed');
